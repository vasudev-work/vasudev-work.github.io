#!/usr/bin/env python3
"""Generate assets/tokens.css: three schemes x three accents, contrast-checked.

The site picks a scheme through html[data-scheme] (set by a small inline script from
the Appearance control) and falls back to prefers-color-scheme when scripting is off.
"""
import pathlib, sys

# base surfaces per scheme
BASE = {
    "light": dict(ink="#14162b", ink_soft="#3d4260", muted="#5f647e", paper="#fbfaf6",
                  surface="#ffffff", surface_quiet="#f4f2ea", line="#e2ded2",
                  indigo="#1b1f45", indigo_solid="#1b1f45", on_indigo="#ffffff",
                  indigo_soft="#eceefb", green="#1f5130", green_soft="#e8f3ea",
                  blue="#1f4d78", blue_soft="#e7eff7",
                  shadow="0 18px 44px rgba(20, 22, 43, .10)",
                  footer_bg="#14162b", footer_ink="#f2f3fb", footer_muted="#b6bad6",
                  color_scheme="light"),
    "dark": dict(ink="#eef0f8", ink_soft="#c5c9dd", muted="#9ba1bf", paper="#0c0e1c",
                 surface="#151933", surface_quiet="#1b2040", line="#2b3157",
                 indigo="#c3c9f2", indigo_solid="#2b3168", on_indigo="#f2f3fb",
                 indigo_soft="#1d2142", green="#8ed6a3", green_soft="#14301f",
                 blue="#9dc3ea", blue_soft="#122639",
                 shadow="0 18px 44px rgba(0, 0, 0, .45)",
                 footer_bg="#06070f", footer_ink="#eef0f8", footer_muted="#a8adc9",
                 color_scheme="dark"),
    # true black for OLED; surfaces stay a hair above #000 so borders still read
    "black": dict(ink="#f2f2f6", ink_soft="#c9c9d2", muted="#9c9caa", paper="#000000",
                  surface="#0a0a0f", surface_quiet="#141419", line="#26262e",
                  indigo="#c3c9f2", indigo_solid="#262a52", on_indigo="#f2f3fb",
                  indigo_soft="#16161d", green="#8ed6a3", green_soft="#0f2417",
                  blue="#9dc3ea", blue_soft="#0d1b28",
                  shadow="0 18px 44px rgba(0, 0, 0, .8)",
                  footer_bg="#000000", footer_ink="#f2f2f6", footer_muted="#a5a5b3",
                  color_scheme="dark"),
}

# accent = (text/accent, soft background, bright border), pill = fill behind white text
ACCENT = {
    "light": {
        "saffron": dict(accent="#9d5711", soft="#fdf3e3", bright="#c9761b", pill="#8a4b0f"),
        "green":   dict(accent="#1f5130", soft="#e8f3ea", bright="#2f7a4a", pill="#1f5130"),
        "indigo":  dict(accent="#262a5c", soft="#eceefb", bright="#3b4189", pill="#262a5c"),
    },
    "dark": {
        "saffron": dict(accent="#f0b566", soft="#2f2415", bright="#f0b566", pill="#a35f10"),
        "green":   dict(accent="#8ed6a3", soft="#14301f", bright="#8ed6a3", pill="#2f7a4a"),
        "indigo":  dict(accent="#aab2e8", soft="#1d2142", bright="#aab2e8", pill="#3b4189"),
    },
    "black": {
        "saffron": dict(accent="#f0b566", soft="#241b0f", bright="#f0b566", pill="#a35f10"),
        "green":   dict(accent="#8ed6a3", soft="#0f2417", bright="#8ed6a3", pill="#2f7a4a"),
        "indigo":  dict(accent="#aab2e8", soft="#16161d", bright="#aab2e8", pill="#3b4189"),
    },
}
ORDER = ["saffron", "green", "indigo"]


def lum(h):
    h = h.lstrip("#")
    c = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    c = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]


def ratio(a, b):
    l1, l2 = sorted([lum(a), lum(b)], reverse=True)
    return (l1 + 0.05) / (l2 + 0.05)


def base_block(scheme):
    b = BASE[scheme]
    lines = [f"  color-scheme: {b['color_scheme']};"]
    for k, v in b.items():
        if k == "color_scheme":
            continue
        lines.append("  --%s: %s;" % (k.replace("_", "-"), v))
    return "\n".join(lines)


def accent_block(scheme, name):
    a = ACCENT[scheme][name]
    return ("  --accent: %s;\n  --accent-soft: %s;\n  --accent-bright: %s;\n  --accent-pill: %s;"
            % (a["accent"], a["soft"], a["bright"], a["pill"]))


def build():
    out = ["/* Generated by _build/tokens.py — do not edit by hand. */",
           "/* Schemes: light, dark, black. Accents: saffron (default), green, indigo. */", ""]

    # default: light + saffron
    out.append(":root {\n%s\n%s\n}" % (base_block("light"), accent_block("light", "saffron")))
    out.append("")

    for scheme in ("light", "dark", "black"):
        out.append('html[data-scheme="%s"] {\n%s\n%s\n}' % (scheme, base_block(scheme), accent_block(scheme, "saffron")))
        for name in ORDER[1:]:
            out.append('html[data-scheme="%s"][data-accent="%s"] {\n%s\n}' % (scheme, name, accent_block(scheme, name)))
        out.append("")

    # no-script fallback: follow the OS, keep the default accent
    out.append("@media (prefers-color-scheme: dark) {\n  html:not([data-scheme]) {\n%s\n%s\n  }\n}"
               % ("\n".join("  " + l for l in base_block("dark").split("\n")),
                  "\n".join("  " + l for l in accent_block("dark", "saffron").split("\n"))))
    out.append("")

    # contrast gate
    fails = []
    for scheme in BASE:
        b = BASE[scheme]
        pairs = [("ink/paper", b["ink"], b["paper"]), ("ink-soft/paper", b["ink_soft"], b["paper"]),
                 ("muted/surface", b["muted"], b["surface"]), ("muted/quiet", b["muted"], b["surface_quiet"]),
                 ("on-indigo/indigo-solid", b["on_indigo"], b["indigo_solid"]),
                 ("footer-muted/footer-bg", b["footer_muted"], b["footer_bg"]),
                 ("green/green-soft", b["green"], b["green_soft"]),
                 ("blue/blue-soft", b["blue"], b["blue_soft"])]
        for name in ORDER:
            a = ACCENT[scheme][name]
            pairs += [("%s accent/paper" % name, a["accent"], b["paper"]),
                      ("%s accent/surface" % name, a["accent"], b["surface"]),
                      ("%s accent/accent-soft" % name, a["accent"], a["soft"]),
                      ("%s white on pill" % name, "#ffffff", a["pill"])]
        for label, fg, bg in pairs:
            r = ratio(fg, bg)
            if r < 4.5:
                fails.append("%-6s %-26s %s on %s = %.2f" % (scheme, label, fg, bg, r))
    if fails:
        print("CONTRAST FAILURES:")
        print("\n".join(fails))
        sys.exit(1)

    path = pathlib.Path(__file__).parent.parent / "assets" / "tokens.css"
    path.write_text("\n".join(out).rstrip() + "\n")
    print("tokens.css written, %d scheme/accent combinations, all pairs >= 4.5:1" % (3 * 3))


if __name__ == "__main__":
    build()
